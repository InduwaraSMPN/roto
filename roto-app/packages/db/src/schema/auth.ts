// 0014 (feature-parity-plan §4.16, §6): better-auth `organization` plugin with
// teams enabled, plus the `admin` and `username` column additions above.
//
// ponytail: the @better-auth/cli package is not installed and our auth setup
// is a factory (createAuth), not a static betterAuth() instance, so the CLI
// cannot scan it. Instead these shapes were produced by calling the
// drizzle-adapter's own generateDrizzleSchema offline with
// organization({ teams: { enabled: true } }), admin(), username() on the
// installed better-auth version, then converted to repo style (double quotes,
// 2-space indent). Table/column/index names are byte-identical to the CLI
// output; only formatting differs. Re-run that dump (not the CLI) if the
// better-auth version or plugin options change, and keep packages/auth in sync.
export const organization = pgTable(
  "organization",
  {
    id: text("id").primaryKey(),
    name: text("name").notNull(),
    slug: text("slug").notNull().unique(),
    logo: text("logo"),
    createdAt: timestamp("created_at").notNull(),
    // ponytail: text-carried JSON ({ kind: 'club' | 'brand', brand? }) — the
    // adapter stringifies on write, so no jsonb needed to match its output
    metadata: text("metadata"),
  },
  (table) => [uniqueIndex("organization_slug_uidx").on(table.slug)],
);

