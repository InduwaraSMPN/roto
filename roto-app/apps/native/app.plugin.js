const { withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

// Release builds target SDK 36, where Android blocks cleartext HTTP outright. That is the correct
// default for production (Roto's API is https), but it also stops a release-mode build from
// reaching a local dev server over http, which is how the emulator smoke test is run. So cleartext
// stays denied globally and is permitted only for the loopback aliases an emulator or dev machine
// uses. This never weakens the shipped app against a real server.
//
// To smoke-test a release build against a laptop on the LAN from a physical phone, add that
// machine's address here (a config plugin cannot express a private CIDR range, only exact hosts).
const CLEAR_TEXT_HOSTS = ["10.0.2.2", "localhost", "127.0.0.1"];

function withRotoNetworkSecurityConfig(config) {
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const resDir = path.join(cfg.modRequest.platformProjectRoot, "app/src/main/res/xml");
      fs.mkdirSync(resDir, { recursive: true });

      const domains = CLEAR_TEXT_HOSTS.map(
        (host) => `    <domain includeSubdomains="true">${host}</domain>`,
      ).join("\n");

      fs.writeFileSync(
        path.join(resDir, "network_security_config.xml"),
        `<?xml version="1.0" encoding="utf-8"?>
<!-- ponytail: generated by apps/native/app.plugin.js - do not edit here. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
${domains}
  </domain-config>
</network-security-config>
`,
      );
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application[0];
    app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    return cfg;
  });
}

module.exports = withRotoNetworkSecurityConfig;
