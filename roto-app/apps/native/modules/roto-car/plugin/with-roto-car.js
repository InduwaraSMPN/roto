// Config plugin for the roto-car local module (Android Auto). Runs at `expo prebuild` /
// `expo run:android` time, against the generated `apps/native/android` project - it never touches
// this module's own `android/` folder (that's compiled as a library, not merged as a manifest).
//
// What it adds to the app's AndroidManifest.xml:
//   - <uses-permission> for androidx.car.app.NAVIGATION_TEMPLATES (required for NavigationTemplate,
//     which is the content pane of MapWithContentTemplate too) and androidx.car.app.ACCESS_SURFACE
//     (required for the AppManager SurfaceCallback that RotoCarMapSurface draws the route into).
//   - a <meta-data androidx.car.app.minCarApiLevel> on <application>.
//   - a <meta-data com.google.android.gms.car.application> on <application> pointing at
//     @xml/automotive_app_desc (the file this plugin also writes).
//   - a <service> for RotoCarAppService with the CarAppService intent-filter and the NAVIGATION
//     category, per https://developer.android.com/training/cars/apps/navigation.
// And one resource file: res/xml/automotive_app_desc.xml.
const { AndroidConfig, withAndroidManifest, withDangerousMod, createRunOncePlugin } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const pkg = require('../package.json');

const SERVICE_NAME = 'expo.modules.rotocar.RotoCarAppService';
const MIN_CAR_API_LEVEL = '1';
const AUTOMOTIVE_APP_DESC_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by roto-car's config plugin (plugin/with-roto-car.js). Do not hand-edit; it is
     overwritten on every prebuild. -->
<automotiveApp>
  <uses name="template" />
</automotiveApp>
`;

const { getMainApplicationOrThrow, addMetaDataItemToMainApplication } = AndroidConfig.Manifest;

function withRotoCarPermissions(config) {
  return AndroidConfig.Permissions.withPermissions(config, [
    'androidx.car.app.NAVIGATION_TEMPLATES',
    'androidx.car.app.ACCESS_SURFACE',
  ]);
}

function withRotoCarManifest(config) {
  return withAndroidManifest(config, (config) => {
    const mainApplication = getMainApplicationOrThrow(config.modResults);

    addMetaDataItemToMainApplication(mainApplication, 'androidx.car.app.minCarApiLevel', MIN_CAR_API_LEVEL);
    addMetaDataItemToMainApplication(
      mainApplication,
      'com.google.android.gms.car.application',
      '@xml/automotive_app_desc',
      'resource'
    );

    if (!Array.isArray(mainApplication.service)) {
      mainApplication.service = [];
    }
    const alreadyDeclared = mainApplication.service.some(
      (service) => service.$?.['android:name'] === SERVICE_NAME
    );
    if (!alreadyDeclared) {
      mainApplication.service.push({
        $: {
          'android:name': SERVICE_NAME,
          'android:exported': 'true',
        },
        'intent-filter': [
          {
            action: [{ $: { 'android:name': 'androidx.car.app.CarAppService' } }],
            category: [{ $: { 'android:name': 'androidx.car.app.category.NAVIGATION' } }],
          },
        ],
      });
    }

    return config;
  });
}

function withRotoCarAutomotiveAppDesc(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const resDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(resDir, { recursive: true });
      fs.writeFileSync(path.join(resDir, 'automotive_app_desc.xml'), AUTOMOTIVE_APP_DESC_XML);
      return config;
    },
  ]);
}

const withRotoCar = (config) => {
  config = withRotoCarPermissions(config);
  config = withRotoCarManifest(config);
  config = withRotoCarAutomotiveAppDesc(config);
  return config;
};

module.exports = createRunOncePlugin(withRotoCar, pkg.name, pkg.version);
