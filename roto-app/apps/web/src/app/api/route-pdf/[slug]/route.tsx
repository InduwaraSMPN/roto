type Lang = keyof typeof STR;

type SharedRoute = {
  name?: string;
  coords?: [number, number][] | null;
  maneuvers?: { instruction?: string; lengthKm?: number; streets?: string[] }[] | null;
  km?: number | null;
  min?: number | null;
  elevation?: { distM?: number[]; heightM?: number[] } | null;
  curvature?: number | null;
  surface?: string | null;
};

function fmtKm(v: number | null | undefined): string {
  return v == null ? "—" : v.toFixed(1);
}

function fmtMin(v: number | null | undefined): string {
  if (v == null) return "—";
  const m = Math.round(v);
  return m >= 60 ? `${Math.floor(m / 60)} h ${m % 60} min` : `${m} min`;
}

export async function GET(request: Request, ctx: { params: Promise<{ slug: string }> }) {
  const { slug } = await ctx.params;
  const langParam = new URL(request.url).searchParams.get("lang");
  const lang: Lang = langParam === "si" || langParam === "ta" ? langParam : "en";
  const t = STR[lang];

  let route: SharedRoute | null = null;
  try {
    route = await serverTrpc.routes.bySlug.query({ slug });
  } catch {
    return new Response("Route not found", { status: 404 });
  }
  const coords = Array.isArray(route?.coords) ? (route!.coords as [number, number][]) : [];
  if (!route || coords.length < 2) return new Response("Route not found", { status: 404 });

  const maneuvers = (Array.isArray(route.maneuvers) ? route.maneuvers : []).filter(Boolean);
  const name = route.name ?? slug;

  // A saved route stores no elevation column, so ask the routing layer for it here. Falls
  // back to the stored profile when one exists (curated rows) and to "no data" when the
  // elevation backend is unavailable, which is the documented D1 prod degradation.
  let profile_ = route.elevation ?? null;
  if (!profile_ && coords.length > 1) {
    try {
      const step = Math.max(1, Math.floor(coords.length / 200));
      const sampled = coords.filter((_, i) => i % step === 0 || i === coords.length - 1);
      const res = await serverTrpc.route.elevation.query({ coords: sampled });
      profile_ = res?.profile ?? null;
    } catch {
      profile_ = null;
    }
  }
  const distM = profile_?.distM;
  const heightM = profile_?.heightM;
  const hasProfile = Array.isArray(distM) && Array.isArray(heightM) && distM.length > 1 && heightM.length > 1;

  // Downsample the profile so the chart has a readable number of points, not 5 000. The x
  // label is the distance in km, so the axis reads as a distance axis rather than a point
  // index.
  const profile: GraphSeries[] | null = hasProfile
    ? [
        {
          name: "m",
          data: (() => {
            // 18 points: the chart labels every x value, so more than that turns the axis
            // into overlapping digits.
            const step = Math.max(1, Math.floor(heightM.length / 18));
            const out: { label: string; value: number }[] = [];
            for (let i = 0; i < heightM.length; i += step) {
              const h = heightM[i] ?? 0;
              out.push({ label: `${((distM?.[i] ?? 0) / 1000).toFixed(0)}`, value: Math.round(h) });
            }
            return out;
          })(),
          color: PDF_LINE_THEME.signal,
        },
      ]
    : null;

  const document = (
    <PdfcnThemeProvider>
      <Stack gap="md">
        <PageHeader
          title={name}
          subtitle={t.subtitle}
          rightText={`${fmtKm(route.km)} km`}
          rightSubText={fmtMin(route.min)}
          variant="minimal"
        />

        <KeyValue
          divided
          size="sm"
          items={[
            { key: t.distance, value: `${fmtKm(route.km)} km` },
            { key: t.estTime, value: fmtMin(route.min) },
            { key: t.turns, value: String(maneuvers.length) },
            // ponytail: a saved route has no surface column, so the row is dropped rather
            // than printing a dash the rider would read as "unknown road".
            ...(route.surface ? [{ key: t.surface, value: route.surface }] : []),
            ...(route.curvature != null
              ? [{ key: t.curve, value: route.curvature.toFixed(2) }]
              : []),
          ]}
        />

        {coordsToPolylineSvg(coords, PDF_LINE_THEME.signal)}

        {hasProfile && profile ? (
          <Section spacing="sm">
            <Heading level={2}>{t.profile}</Heading>
            <PdfGraph
              variant="area"
              data={profile}
              // ponytail: the unit goes in the subtitle, not yLabel — the chart draws the
              // y-axis label on top of the topmost tick value.
              subtitle={t.elevationUnit}
              height={130}
              fullWidth
              showGrid={false}
              showDots={false}
              smooth
              legend="none"
            />
          </Section>
        ) : (
          <Section spacing="sm">
            <Heading level={2}>{t.profile}</Heading>
            <Text variant="sm">{t.noProfile}</Text>
          </Section>
        )}

        <Section spacing="sm">
          <Heading level={2}>{t.heading}</Heading>
          {maneuvers.length === 0 ? (
            <Text variant="sm">{t.noTurns}</Text>
          ) : (
            <Table variant="line">
              <TableHeader>
                <TableRow header variant="line">
                  <TableCell header variant="line" width={40} align="right">
                    {t.step}
                  </TableCell>
                  <TableCell header variant="line">
                    {t.instruction}
                  </TableCell>
                  <TableCell header variant="line" width={70} align="right">
                    {t.length}
                  </TableCell>
                </TableRow>
              </TableHeader>
              <TableBody>
                {maneuvers.slice(0, 120).map((m, i) => (
                  <TableRow key={i} variant="line">
                    <TableCell variant="line" width={40} align="right">
                      {String(i + 1)}
                    </TableCell>
                    <TableCell variant="line">{m.instruction || "Continue"}</TableCell>
                    <TableCell variant="line" width={70} align="right">
                      {m.lengthKm != null ? `${m.lengthKm.toFixed(1)} km` : "—"}
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          )}
        </Section>

        <Section spacing="sm">
          <Heading level={2}>{t.emergency}</Heading>
          <KeyValue
            size="sm"
            items={[
              { key: t.police, value: "119" },
              { key: t.ambulance, value: "1990" },
              { key: t.fire, value: "110" },
            ]}
          />
        </Section>

        <Divider />
        <Badge variant="outline">ROTO</Badge>
        <Text variant="xs">{t.attribution}</Text>
        <PageFooter
          centerText={
            <PDFText>
              {t.generated} · <PageNumber />
            </PDFText>
          }
        />
      </Stack>
    </PdfcnThemeProvider>
  );

  // Registered fonts cover Sinhala and Tamil; without them takumi throws on the si/ta sheets.
  const fonts = await pdfFonts();
  const pdf = await render(document, {
    size: "a4",
    margin: { top: 40, right: 32, bottom: 40, left: 32 },
    ...(fonts.length ? { fonts } : {}),
  });

  return new Response(pdf as BodyInit, {
    headers: {
      "content-type": "application/pdf",
      "content-disposition": `inline; filename="roto-${slug}.pdf"`,
      "cache-control": "public, max-age=300",
    },
  });
}
